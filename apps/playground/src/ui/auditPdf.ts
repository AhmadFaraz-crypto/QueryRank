// Builds a downloadable PDF of an SEO audit report, laid out as real text with
// jsPDF (so it's crisp, small, and selectable — not a screenshot). Grouped by
// category, with each issue's finding and recommended fix.

import { jsPDF } from 'jspdf'
import type { AuditReport, Category, Check, Severity, SiteReport } from './auditApi'

const INK: [number, number, number] = [23, 26, 31]
const MUTE: [number, number, number] = [120, 125, 135]
const ACCENT: [number, number, number] = [39, 44, 53]
const SEV: Record<Severity, [number, number, number]> = {
  good: [31, 150, 90],
  warning: [193, 138, 0],
  error: [209, 67, 67],
}
const SEV_LABEL: Record<Severity, string> = { good: 'PASS', warning: 'WARN', error: 'FAIL' }

const CATEGORY_ORDER: Category[] = ['Indexability', 'Meta', 'Content', 'Social', 'Technical']

function hostOf(u: string): string {
  try {
    return new URL(u).host
  } catch {
    return u
  }
}

function scoreBand(score: number): string {
  if (score >= 80) return 'Good'
  if (score >= 50) return 'Needs work'
  return 'Poor'
}

function scoreColor(score: number): [number, number, number] {
  if (score >= 80) return SEV.good
  if (score >= 50) return SEV.warning
  return SEV.error
}

export function buildAuditPdf(report: AuditReport): { doc: jsPDF; filename: string } {
  const doc = new jsPDF({ unit: 'pt', format: 'a4' })
  const W = doc.internal.pageSize.getWidth()
  const H = doc.internal.pageSize.getHeight()
  const M = 48
  const contentW = W - M * 2
  let y = 0

  const addFooter = () => {
    const pages = doc.getNumberOfPages()
    for (let p = 1; p <= pages; p++) {
      doc.setPage(p)
      doc.setFont('helvetica', 'normal').setFontSize(8).setTextColor(...MUTE)
      doc.text('Generated by QueryRank · getqueryrank.com', M, H - 24)
      doc.text(`Page ${p} of ${pages}`, W - M, H - 24, { align: 'right' })
    }
  }

  const ensure = (needed: number) => {
    if (y + needed > H - 48) {
      doc.addPage()
      y = M
    }
  }

  // --- Header band ----------------------------------------------------------
  doc.setFillColor(...ACCENT).rect(0, 0, W, 92, 'F')
  doc.setFont('helvetica', 'bold').setFontSize(16).setTextColor(255, 255, 255)
  doc.text('QueryRank', M, 40)
  doc.setFont('helvetica', 'normal').setFontSize(11).setTextColor(205, 210, 218)
  doc.text('SEO Audit Report', M, 60)
  const auditedOn = new Date(report.fetchedAt).toLocaleString()
  doc.setFontSize(9).setTextColor(180, 186, 196)
  doc.text(auditedOn, W - M, 40, { align: 'right' })
  y = 128

  // --- URL + score ----------------------------------------------------------
  doc.setFont('helvetica', 'bold').setFontSize(15).setTextColor(...INK)
  doc.text(hostOf(report.finalUrl), M, y)
  doc.setFont('helvetica', 'normal').setFontSize(9).setTextColor(...MUTE)
  const urlLines = doc.splitTextToSize(report.finalUrl, contentW - 130)
  doc.text(urlLines, M, y + 16)

  // Score block (right aligned)
  const sc = scoreColor(report.score)
  doc.setFont('helvetica', 'bold').setFontSize(34).setTextColor(...sc)
  doc.text(String(report.score), W - M, y + 6, { align: 'right' })
  const scW = doc.getTextWidth(String(report.score))
  doc.setFontSize(12).setTextColor(...MUTE)
  doc.text('/100', W - M, y + 22, { align: 'right' })
  doc.setFont('helvetica', 'bold').setFontSize(9).setTextColor(...sc)
  doc.text(scoreBand(report.score).toUpperCase(), W - M - scW - 34, y + 6, { align: 'right' })

  y += 16 + urlLines.length * 11 + 14

  // Summary chips line
  doc.setFont('helvetica', 'normal').setFontSize(10).setTextColor(...INK)
  const { good, warning, error, total } = report.counts
  doc.text(
    `${good} passed   ·   ${warning} warnings   ·   ${error} errors   ·   ${total} checks`,
    M,
    y,
  )
  y += 10

  // meta line
  doc.setFontSize(8.5).setTextColor(...MUTE)
  doc.text(
    `HTTP ${report.status}${report.redirects ? ` · ${report.redirects} redirect(s)` : ''} · ${(
      report.elapsedMs / 1000
    ).toFixed(2)}s · ${Math.round(report.pageBytes / 1024)} KB`,
    M,
    y + 12,
  )
  y += 30
  doc.setDrawColor(228, 231, 235).line(M, y, W - M, y)
  y += 22

  // --- Checks grouped by category ------------------------------------------
  const byCat = (cat: Category) => report.checks.filter((c) => c.category === cat)

  const drawCheck = (c: Check) => {
    const sev = SEV[c.severity]
    const detailLines = doc.splitTextToSize(c.detail, contentW - 86) as string[]
    const recLines = c.recommendation
      ? (doc.splitTextToSize(`Fix: ${c.recommendation}`, contentW - 86) as string[])
      : []
    const blockH = 16 + detailLines.length * 11 + (recLines.length ? 4 + recLines.length * 11 : 0) + 12
    ensure(blockH)

    // severity tag
    doc.setFillColor(...sev).roundedRect(M, y - 9, 34, 14, 3, 3, 'F')
    doc.setFont('helvetica', 'bold').setFontSize(7).setTextColor(255, 255, 255)
    doc.text(SEV_LABEL[c.severity], M + 17, y + 1, { align: 'center' })

    // label
    doc.setFont('helvetica', 'bold').setFontSize(10.5).setTextColor(...INK)
    doc.text(c.label, M + 46, y + 1)
    y += 16

    // detail
    doc.setFont('helvetica', 'normal').setFontSize(9.5).setTextColor(70, 74, 82)
    doc.text(detailLines, M + 46, y)
    y += detailLines.length * 11

    // recommendation
    if (recLines.length) {
      y += 4
      doc.setFont('helvetica', 'italic').setFontSize(9).setTextColor(...sev)
      doc.text(recLines, M + 46, y)
      y += recLines.length * 11
    }
    y += 12
  }

  for (const cat of CATEGORY_ORDER) {
    const items = byCat(cat)
    if (!items.length) continue
    ensure(40)
    doc.setFont('helvetica', 'bold').setFontSize(8).setTextColor(...MUTE)
    doc.text(cat.toUpperCase(), M, y)
    y += 6
    doc.setDrawColor(228, 231, 235).line(M, y, W - M, y)
    y += 18
    for (const c of items) drawCheck(c)
    y += 6
  }

  addFooter()

  const stamp = new Date(report.fetchedAt).toISOString().slice(0, 10)
  return { doc, filename: `seo-audit-${hostOf(report.finalUrl).replace(/[^a-z0-9.-]/gi, '_')}-${stamp}.pdf` }
}

export function downloadAuditPdf(report: AuditReport): void {
  const { doc, filename } = buildAuditPdf(report)
  doc.save(filename)
}

/** Build a whole-site crawl report PDF; returns the doc + filename. */
export function buildSitePdf(report: SiteReport): { doc: jsPDF; filename: string } {
  const doc = new jsPDF({ unit: 'pt', format: 'a4' })
  const W = doc.internal.pageSize.getWidth()
  const H = doc.internal.pageSize.getHeight()
  const M = 48
  const contentW = W - M * 2
  let y = 0

  const addFooter = () => {
    const pages = doc.getNumberOfPages()
    for (let p = 1; p <= pages; p++) {
      doc.setPage(p)
      doc.setFont('helvetica', 'normal').setFontSize(8).setTextColor(...MUTE)
      doc.text('Generated by QueryRank · getqueryrank.com', M, H - 24)
      doc.text(`Page ${p} of ${pages}`, W - M, H - 24, { align: 'right' })
    }
  }
  const ensure = (needed: number) => {
    if (y + needed > H - 48) {
      doc.addPage()
      y = M
    }
  }

  // Header band
  doc.setFillColor(...ACCENT).rect(0, 0, W, 92, 'F')
  doc.setFont('helvetica', 'bold').setFontSize(16).setTextColor(255, 255, 255)
  doc.text('QueryRank', M, 40)
  doc.setFont('helvetica', 'normal').setFontSize(11).setTextColor(205, 210, 218)
  doc.text('Site SEO Audit', M, 60)
  doc.setFontSize(9).setTextColor(180, 186, 196)
  doc.text(new Date(report.crawledAt).toLocaleString(), W - M, 40, { align: 'right' })
  y = 128

  // Site + average score
  doc.setFont('helvetica', 'bold').setFontSize(15).setTextColor(...INK)
  doc.text(hostOf(report.site), M, y)
  const sc = scoreColor(report.avgScore)
  doc.setFont('helvetica', 'bold').setFontSize(34).setTextColor(...sc)
  doc.text(String(report.avgScore), W - M, y + 6, { align: 'right' })
  const scW = doc.getTextWidth(String(report.avgScore))
  doc.setFontSize(12).setTextColor(...MUTE)
  doc.text('avg / 100', W - M, y + 22, { align: 'right' })
  doc.setFont('helvetica', 'bold').setFontSize(9).setTextColor(...sc)
  doc.text(scoreBand(report.avgScore).toUpperCase(), W - M - scW - 56, y + 6, { align: 'right' })
  y += 22

  doc.setFont('helvetica', 'normal').setFontSize(10).setTextColor(...INK)
  doc.text(
    `${report.pagesCrawled} pages crawled${report.capped ? ` of ${report.pagesDiscovered} discovered` : ''}   ·   ` +
      `${report.counts.good} passed · ${report.counts.warning} warnings · ${report.counts.error} errors`,
    M,
    y,
  )
  y += 24
  doc.setDrawColor(228, 231, 235).line(M, y, W - M, y)
  y += 22

  // Most common issues
  doc.setFont('helvetica', 'bold').setFontSize(8).setTextColor(...MUTE)
  doc.text('MOST COMMON ISSUES', M, y)
  y += 16
  if (!report.commonIssues.length) {
    doc.setFont('helvetica', 'normal').setFontSize(10).setTextColor(...SEV.good)
    doc.text('No recurring issues found across the crawled pages.', M, y)
    y += 18
  }
  for (const issue of report.commonIssues) {
    ensure(20)
    const sev = SEV[issue.severity]
    doc.setFillColor(...sev).roundedRect(M, y - 9, 34, 14, 3, 3, 'F')
    doc.setFont('helvetica', 'bold').setFontSize(7).setTextColor(255, 255, 255)
    doc.text(SEV_LABEL[issue.severity], M + 17, y + 1, { align: 'center' })
    doc.setFont('helvetica', 'normal').setFontSize(10).setTextColor(...INK)
    doc.text(issue.label, M + 46, y + 1)
    doc.setTextColor(...MUTE)
    doc.text(`${issue.pages} page${issue.pages > 1 ? 's' : ''}`, W - M, y + 1, { align: 'right' })
    y += 18
  }
  y += 10

  // Per-page breakdown — each page followed by its actual issues + fixes.
  ensure(40)
  doc.setFont('helvetica', 'bold').setFontSize(8).setTextColor(...MUTE)
  doc.text('PAGES & ISSUES (WORST FIRST)', M, y)
  y += 6
  doc.setDrawColor(228, 231, 235).line(M, y, W - M, y)
  y += 20

  for (const p of report.pages) {
    const issues = p.error ? [] : p.checks.filter((c) => c.severity !== 'good')
    ensure(30)

    // Page header: score badge + path + issue count.
    const col = p.error ? SEV.error : scoreColor(p.score)
    doc.setFillColor(...col).roundedRect(M, y - 10, 30, 16, 3, 3, 'F')
    doc.setFont('helvetica', 'bold').setFontSize(9).setTextColor(255, 255, 255)
    doc.text(p.error ? '—' : String(p.score), M + 15, y + 1, { align: 'center' })

    doc.setFont('helvetica', 'bold').setFontSize(10).setTextColor(...INK)
    const path = p.url.replace(/^https?:\/\/[^/]+/, '') || '/'
    doc.text((doc.splitTextToSize(path, contentW - 120) as string[])[0], M + 40, y + 1)

    doc.setFont('helvetica', 'normal').setFontSize(8).setTextColor(...MUTE)
    doc.text(
      p.error ? 'unreachable' : issues.length ? `${issues.length} issue${issues.length > 1 ? 's' : ''}` : 'all checks passed',
      W - M,
      y + 1,
      { align: 'right' },
    )
    y += 20

    // The page's issues, each with its finding and recommended fix.
    for (const c of issues) {
      const sev = SEV[c.severity]
      const text = c.recommendation ? `${c.detail}   Fix: ${c.recommendation}` : c.detail
      const lines = doc.splitTextToSize(text, contentW - 26) as string[]
      ensure(13 + lines.length * 10 + 4)
      doc.setFillColor(...sev).circle(M + 10, y - 3, 2.2, 'F')
      doc.setFont('helvetica', 'bold').setFontSize(9).setTextColor(...sev)
      doc.text(`${SEV_LABEL[c.severity]}  ${c.label}`, M + 18, y)
      y += 12
      doc.setFont('helvetica', 'normal').setFontSize(8.5).setTextColor(92, 96, 104)
      doc.text(lines, M + 18, y)
      y += lines.length * 10 + 6
    }
    if (p.error) {
      ensure(14)
      doc.setFont('helvetica', 'italic').setFontSize(8.5).setTextColor(...SEV.error)
      doc.text(p.error, M + 18, y)
      y += 12
    }
    y += 8
  }

  addFooter()
  const stamp = new Date(report.crawledAt).toISOString().slice(0, 10)
  return { doc, filename: `site-audit-${hostOf(report.site).replace(/[^a-z0-9.-]/gi, '_')}-${stamp}.pdf` }
}

export function downloadSitePdf(report: SiteReport): void {
  const { doc, filename } = buildSitePdf(report)
  doc.save(filename)
}
